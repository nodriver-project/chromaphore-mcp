// Generates docs/MAP.md from server/src, plugin/, tools/, and server/test.
// Usage:
//   node tools/map.mjs            # writes docs/MAP.md
//   node tools/map.mjs --check    # exits 1 if docs/MAP.md is missing or stale
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const RANKS = {
  'cdp.ts': 0,
  'paths.ts': 0,
  'listing.ts': 0,
  'launcher.ts': 1,
  'video.ts': 1,
  'browser.ts': 1,
  'install.ts': 2,
  'canvas.ts': 2,
  'editors/index.ts': 3,
  'editors/docs.ts': 3,
  'actions.ts': 4,
  'browser_tools.ts': 4,
  'server.ts': 5,
};

const LAYER_NAMES = ['foundation', 'runtime', 'capabilities', 'editors', 'actions', 'entrypoint'];

function listFiles(dir, ext) {
  const out = [];
  if (!fs.existsSync(dir)) return out;
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, ent.name);
    if (ent.isDirectory()) {
      out.push(...listFiles(full, ext));
    } else if (!ext || ent.name.endsWith(ext)) {
      out.push(full);
    }
  }
  return out;
}

function firstSentence(text) {
  const lines = text.split('\n');
  const commentLines = [];
  for (const line of lines) {
    const trimmed = line.trim();
    if (trimmed.startsWith('//')) {
      const body = trimmed.replace(/^\/\/\s?/, '').trim();
      if (!body) {
        if (commentLines.length) break;
        continue;
      }
      if (/^Usage:/i.test(body)) break;
      commentLines.push(body);
    } else if (!trimmed && commentLines.length === 0) {
      continue;
    } else {
      break;
    }
  }
  if (!commentLines.length) return '(no header comment)';
  const joined = commentLines.join(' ').replace(/\s+/g, ' ').trim();
  const m = /^(.+?\.)(?:\s|$)/.exec(joined);
  const sentence = m ? m[1] : joined;
  return sentence.length > 180 ? sentence.slice(0, 177) + '...' : sentence;
}

function extractExports(text) {
  const names = [];
  const re = /^export\s+(?:async\s+)?(?:function|class|const|let|type|interface|enum)\s+(\w+)/gm;
  let m;
  while ((m = re.exec(text))) names.push(m[1]);
  return names;
}

function extractLocalImports(text) {
  const imps = [];
  const re = /from\s+['"](\.[^'"]+)['"]/g;
  let m;
  while ((m = re.exec(text))) {
    if (!imps.includes(m[1])) imps.push(m[1]);
  }
  return imps;
}

function escapeCell(s) {
  return s.replace(/\|/g, '\\|');
}

export function generateMap(repoRoot) {
  const srcDir = path.join(repoRoot, 'server', 'src');
  const testDir = path.join(repoRoot, 'server', 'test');
  const toolsDir = path.join(repoRoot, 'tools');

  const srcFiles = listFiles(srcDir, '.ts')
    .map((f) => path.relative(srcDir, f).replace(/\\/g, '/'))
    .sort((a, b) => {
      const ra = RANKS[a] ?? 99;
      const rb = RANKS[b] ?? 99;
      return ra !== rb ? ra - rb : a.localeCompare(b);
    });

  const lines = [
    '<!-- GENERATED by tools/map.mjs. Do not edit by hand: run `node tools/map.mjs`. -->',
    '# Repository Map',
    '',
    'Generated index of `server/src/`, `tools/`, `plugin/`, and `server/test/`.',
    '',
    '## Source modules (`server/src/`)',
    '',
    '| Layer | Module | Lines | Summary | Local imports |',
    '|---|---|---:|---|---|',
  ];

  for (const rel of srcFiles) {
    const text = fs.readFileSync(path.join(srcDir, rel), 'utf8').replace(/\r\n/g, '\n');
    const lineCount = text.split('\n').length - (text.endsWith('\n') ? 1 : 0);
    const rank = RANKS[rel];
    const layer = rank !== undefined ? `${rank} (${LAYER_NAMES[rank]})` : 'unranked';
    const summary = escapeCell(firstSentence(text));
    const imps = extractLocalImports(text).map((i) => `\`${i}\``).join(', ') || '—';
    lines.push(`| ${layer} | \`server/src/${rel}\` | ${lineCount} | ${summary} | ${imps} |`);
  }

  lines.push('', '### Key exports by module', '');
  for (const rel of srcFiles) {
    const text = fs.readFileSync(path.join(srcDir, rel), 'utf8').replace(/\r\n/g, '\n');
    const exps = extractExports(text);
    const shown = exps.length ? exps.map((e) => `\`${e}\``).join(', ') : '(entrypoint, no exports)';
    lines.push(`- \`server/src/${rel}\`: ${shown}`);
  }

  lines.push('', '## Repo tooling (`tools/` and `server/build.mjs`)', '', '| Script | Purpose |', '|---|---|');
  const buildPath = path.join(repoRoot, 'server', 'build.mjs');
  if (fs.existsSync(buildPath)) {
    const text = fs.readFileSync(buildPath, 'utf8').replace(/\r\n/g, '\n');
    lines.push(`| \`server/build.mjs\` | ${escapeCell(firstSentence(text))} |`);
  }
  const toolFiles = listFiles(toolsDir, '.mjs')
    .map((f) => path.relative(repoRoot, f).replace(/\\/g, '/'))
    .sort();
  for (const rel of toolFiles) {
    const text = fs.readFileSync(path.join(repoRoot, rel), 'utf8').replace(/\r\n/g, '\n');
    lines.push(`| \`${rel}\` | ${escapeCell(firstSentence(text))} |`);
  }

  lines.push('', '## Plugin deliverables (`plugin/` and `.claude-plugin/`)', '', '| Path | Role |', '|---|---|');
  const pluginEntries = [
    ['.claude-plugin/marketplace.json', 'Claude Code marketplace manifest pointing at `./plugin`'],
    ['plugin/.claude-plugin/plugin.json', 'Plugin manifest, version, and `userConfig` (`browser_path`, `replay_options`)'],
    ['plugin/.mcp.json', 'MCP server command (`node ${CLAUDE_PLUGIN_ROOT}/dist/server.mjs`) and env wiring'],
    ['plugin/dist/server.mjs', 'Bundled MCP server (generated by `server/build.mjs`)'],
    ['plugin/dist/launcher.mjs', 'Bundled detached browser launcher (generated by `server/build.mjs`)'],
    ['plugin/skills/browser/SKILL.md', 'Agent guidance skill for driving the browser tools'],
    ['plugin/skills/install/SKILL.md', 'Agent guidance skill for `browser_install`'],
    ['plugin/THIRD_PARTY_NOTICES.md', 'Bundled npm dependency licences (generated by `server/build.mjs`)'],
  ];
  for (const [rel, role] of pluginEntries) {
    if (fs.existsSync(path.join(repoRoot, rel))) {
      lines.push(`| \`${rel}\` | ${role} |`);
    }
  }

  const testFiles = listFiles(testDir, '.mjs')
    .map((f) => path.relative(testDir, f).replace(/\\/g, '/'))
    .sort();
  const unitTests = testFiles.filter((f) => f.endsWith('_unit.mjs'));
  const liveTests = testFiles.filter((f) => !f.endsWith('_unit.mjs'));

  lines.push('', '## Unit tests — browserless, run in CI (`server/test/*_unit.mjs`)', '', '| Suite | Covers |', '|---|---|');
  for (const rel of unitTests) {
    const text = fs.readFileSync(path.join(testDir, rel), 'utf8').replace(/\r\n/g, '\n');
    lines.push(`| \`server/test/${rel}\` | ${escapeCell(firstSentence(text))} |`);
  }

  lines.push('', '## Live tests — require Chromaphore (`server/test/*.mjs`)', '', '| Suite | Covers |', '|---|---|');
  for (const rel of liveTests) {
    const text = fs.readFileSync(path.join(testDir, rel), 'utf8').replace(/\r\n/g, '\n');
    lines.push(`| \`server/test/${rel}\` | ${escapeCell(firstSentence(text))} |`);
  }

  lines.push('');
  return lines.join('\n');
}

function main(argv) {
  let check = false;
  let root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--check') check = true;
    else if (argv[i] === '--root' && argv[i + 1]) root = path.resolve(argv[++i]);
    else {
      console.error(`Usage: node tools/map.mjs [--check] [--root <dir>]`);
      return 2;
    }
  }
  const mapPath = path.join(root, 'docs', 'MAP.md');
  const next = generateMap(root);
  if (check) {
    const current = fs.existsSync(mapPath) ? fs.readFileSync(mapPath, 'utf8') : null;
    if (current !== next) {
      console.error('docs/MAP.md:1: MAP docs/MAP.md is missing or stale; run `node tools/map.mjs`');
      return 1;
    }
    console.log('docs/MAP.md: up to date');
    return 0;
  }
  fs.mkdirSync(path.dirname(mapPath), { recursive: true });
  fs.writeFileSync(mapPath, next, 'utf8');
  console.log(`wrote docs/MAP.md (${Buffer.byteLength(next, 'utf8')} bytes)`);
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exit(main(process.argv.slice(2)));
}
